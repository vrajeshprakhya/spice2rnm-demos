  //--------------------------------------------------------------------
  // CLASS: rc_lpf2_ms_transaction
  //
  // One analog operating point.  The stimulus is an INDEX into the golden
  // table rather than a `rand real` level: IEEE 1800-2017 18.4 restricts
  // rand to integral types (real rand is an 1800-2023 addition), and
  // indexing also guarantees every randomized stimulus has a golden to
  // check against.
  //--------------------------------------------------------------------
  typedef enum { OP_DC, OP_AC, OP_DUTY } op_kind_e;

  class rc_lpf2_ms_transaction extends uvm_sequence_item;

    rand op_kind_e    kind;
    rand int unsigned gold_idx;   // index into the DC table when kind == OP_DC
    rand int unsigned ac_idx;     // index into the AC table when kind == OP_AC
    rand int unsigned duty_idx;   // index into the duty table, kind == OP_DUTY

    real level;       // DC stimulus driven, volts
    real response;    // DC response, volts        (filled by the monitor)
    real freq;        // AC or clock frequency, Hz
    real mag_db;      // AC gain magnitude, dB     (filled by the monitor)
    real phase_deg;   // AC phase, degrees         (filled by the monitor)
    real in_duty;     // duty driven into the block, fraction
    real out_duty;    // duty measured out         (filled by the monitor)
    real vth;         // threshold this point is sliced at, volts

    `uvm_object_utils_begin(rc_lpf2_ms_transaction)
      `uvm_field_enum(op_kind_e, kind, UVM_DEFAULT)
      `uvm_field_int (gold_idx,  UVM_DEFAULT)
      `uvm_field_int (ac_idx,    UVM_DEFAULT)
      `uvm_field_int (duty_idx,  UVM_DEFAULT)
      `uvm_field_real(level,     UVM_DEFAULT)
      `uvm_field_real(response,  UVM_DEFAULT)
      `uvm_field_real(freq,      UVM_DEFAULT)
      `uvm_field_real(mag_db,    UVM_DEFAULT)
      `uvm_field_real(phase_deg, UVM_DEFAULT)
      `uvm_field_real(in_duty,   UVM_DEFAULT)
      `uvm_field_real(out_duty,  UVM_DEFAULT)
      `uvm_field_real(vth,       UVM_DEFAULT)
    `uvm_object_utils_end

    constraint gold_idx_c { gold_idx inside {[0:GOLD_N-1]}; }
    constraint ac_idx_c   { AC_N > 0 -> ac_idx inside {[0:AC_N-1]};
                            AC_N == 0 -> ac_idx == 0; }
    constraint duty_idx_c { DUTY_N > 0 -> duty_idx inside {[0:DUTY_N-1]};
                            DUTY_N == 0 -> duty_idx == 0; }
    // Never randomize into a mode that has no golden behind it: a check
    // with nothing to compare against is a pass that means nothing.
    constraint kind_c     { AC_N == 0   -> kind != OP_AC;
                            DUTY_N == 0 -> kind != OP_DUTY; }

    function new(string name = "rc_lpf2_ms_transaction");
      super.new(name);
    endfunction

    // Must be virtual: a non-virtual post_randomize leaves a
    // factory-overridden item's own fields at zero.
    virtual function void post_randomize();
      level = gold_x(gold_idx);
      if (kind == OP_DUTY && DUTY_N > 0) begin
        freq    = duty_freq(duty_idx);
        in_duty = duty_in(duty_idx);
        vth     = duty_vth(duty_idx);
      end else begin
        freq = (AC_N > 0) ? ac_freq(ac_idx) : 0.0;
      end
    endfunction

    virtual function string convert2string();
      if (kind == OP_DUTY)
        return $sformatf("DUTY idx = %0d, freq = %0.6g Hz, in = %0.2f%%, out = %0.2f%%",
                         duty_idx, freq, 100.0 * in_duty, 100.0 * out_duty);
      if (kind == OP_AC)
        return $sformatf("AC  idx = %0d, freq = %0.6g Hz, mag = %0.4f dB, phase = %0.2f deg",
                         ac_idx, freq, mag_db, phase_deg);
      return $sformatf("DC  idx = %0d, level = %0.6f V, response = %0.6f V",
                       gold_idx, level, response);
    endfunction

  endclass : rc_lpf2_ms_transaction

  //--------------------------------------------------------------------
  // CLASS: rc_lpf2_ms_driver
  //
  // Pushes the level through the proxy (6.2.4) and then holds the item
  // until the core reports a settled sample (6.2.5 push-sync), rather
  // than guessing a delay.
  //--------------------------------------------------------------------
  class rc_lpf2_ms_driver extends uvm_driver #(rc_lpf2_ms_transaction);

    protected rc_lpf2_proxy bridge_proxy;
    int num_sent = 0;

    `uvm_component_utils(rc_lpf2_ms_driver)

    function new(string name, uvm_component parent);
      super.new(name, parent);
    endfunction

    virtual function void connect_phase(uvm_phase phase);
      super.connect_phase(phase);
      if (!uvm_config_db #(rc_lpf2_proxy)::get(this, "", "bridge_proxy", bridge_proxy))
        `uvm_fatal(get_type_name(), "bridge proxy not configured")
    endfunction

    virtual task run_phase(uvm_phase phase);
      forever begin
        seq_item_port.get_next_item(req);
        drive_transaction(req);
        seq_item_port.item_done();
      end
    endtask

    virtual task drive_transaction(rc_lpf2_ms_transaction txn);
      num_sent++;
      `uvm_info(get_type_name(),
                $sformatf("pushing %s", txn.convert2string()), UVM_MEDIUM)
      if (txn.kind == OP_DUTY)
        bridge_proxy.push_duty(.freq(txn.freq), .in_duty(txn.in_duty),
                               .v_lo(DUTY_VLO), .v_hi(DUTY_VHI),
                               .vth(txn.vth));
      else if (txn.kind == OP_AC)
        bridge_proxy.push_ac(.freq(txn.freq), .ampl(AC_AMPL), .bias(AC_BIAS));
      else
        bridge_proxy.push(.level(txn.level), .enable(1'b1));
      bridge_proxy.wait_sampling_done();
    endtask

  endclass : rc_lpf2_ms_driver

  //--------------------------------------------------------------------
  // CLASS: rc_lpf2_ms_monitor
  //
  // 6.2.2 continuous monitoring: waits on the core's handshake and pulls
  // both what was driven and what was measured (6.2.6), so the scoreboard
  // never has to trust the driver's copy of the stimulus.
  //--------------------------------------------------------------------
  class rc_lpf2_ms_monitor extends uvm_monitor;

    protected rc_lpf2_proxy bridge_proxy;
    uvm_analysis_port #(rc_lpf2_ms_transaction) item_collected_port;
    int num_col = 0;

    `uvm_component_utils(rc_lpf2_ms_monitor)

    function new(string name, uvm_component parent);
      super.new(name, parent);
      item_collected_port = new("item_collected_port", this);
    endfunction

    virtual function void connect_phase(uvm_phase phase);
      super.connect_phase(phase);
      if (!uvm_config_db #(rc_lpf2_proxy)::get(this, "", "bridge_proxy", bridge_proxy))
        `uvm_fatal(get_type_name(), "bridge proxy not configured")
    endfunction

    virtual task run_phase(uvm_phase phase);
      rc_lpf2_ms_transaction txn;
      forever begin
        bridge_proxy.wait_sampling_done();

        txn = rc_lpf2_ms_transaction::type_id::create("txn", this);
        void'(begin_tr(txn, "analog operating point"));

        if (bridge_proxy.get_is_duty()) begin
          txn.kind     = OP_DUTY;
          txn.freq     = bridge_proxy.get_stimulus();
          txn.in_duty  = bridge_proxy.get_in_duty();
          txn.out_duty = bridge_proxy.get_duty();
        end else if (bridge_proxy.get_is_ac()) begin
          txn.kind      = OP_AC;
          txn.freq      = bridge_proxy.get_stimulus();
          txn.mag_db    = bridge_proxy.get_mag_db();
          txn.phase_deg = bridge_proxy.get_phase_deg();
        end else begin
          txn.kind     = OP_DC;
          txn.level    = bridge_proxy.get_stimulus();
          txn.response = bridge_proxy.get_response();
        end

        num_col++;
        `uvm_info(get_type_name(),
                  $sformatf("collected %s", txn.convert2string()), UVM_HIGH)
        item_collected_port.write(txn);
        end_tr(txn);
      end
    endtask

  endclass : rc_lpf2_ms_monitor

