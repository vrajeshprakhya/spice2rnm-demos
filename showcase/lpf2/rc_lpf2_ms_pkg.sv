  // SEQUENCE: randomized operating points.  Same golden table, visited in
  // a random order with repeats -- exercises the push path the way an
  // integrating testbench would rather than as a tidy monotonic ramp.
  //--------------------------------------------------------------------
  class rc_lpf2_ms_random_seq extends uvm_sequence #(rc_lpf2_ms_transaction);

    rand int unsigned n_items;
    constraint n_items_c { n_items inside {[8:24]}; }

    `uvm_object_utils(rc_lpf2_ms_random_seq)

    function new(string name = "rc_lpf2_ms_random_seq");
      super.new(name);
    endfunction

    virtual task body();
      rc_lpf2_ms_transaction txn;
      if (n_items == 0) n_items = 16;
      repeat (n_items) begin
        txn = rc_lpf2_ms_transaction::type_id::create("txn");
        start_item(txn);
        if (!txn.randomize())
          `uvm_error("SEQ", "randomization of the operating point failed")
        finish_item(txn);
      end
    endtask

  endclass : rc_lpf2_ms_random_seq

