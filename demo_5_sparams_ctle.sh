#!/usr/bin/env bash
# DEMO 5 -- S-parameters: a CTLE's differential transmission, modelled.
#
# The claim, stated before anything runs so it can be checked against
# what follows: THE GENERATED MODEL REPRODUCES THE BLOCK'S DIFFERENTIAL
# TRANSMISSION, SDD21, measured from the shipped model in the
# SystemVerilog simulator. PORT MATCH (SDD11, SDD22) AND MODE CONVERSION
# ARE MEASURED FROM THE TRANSISTORS AND REPORTED, NOT MODELLED.
#
# That split is the model form, not modesty. An RNM net carries one real
# value per tick and the value flows one way; an S-parameter port carries
# two travelling waves, each way, normalised to a reference impedance.
# A reflection coefficient has nowhere to live in a real-number net, so
# act 5 reads out what the model does not cover rather than leaving it
# absent.
#
#   DEMO_PAUSE=1 ./demo_5_sparams_ctle.sh   pause between acts

set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
S2R="${S2R:-$HOME/spice2rnm}"
NGSPICE="${NGSPICE:-$HOME/ngspice-install/bin/ngspice}"
XEZIM="${XEZIM:-$HOME/xezim/target/release/xezim}"
# matplotlib is an optional extra of the tool, so the plots are optional
# here too: without it every number still lands in the CSV and verdict.
PYPLOT="${PYPLOT:-$HOME/.s2r-plots/bin/python3}"
OUT="$HOME/s2r_runs/ctle_sparams"
NETLIST="$HERE/netlists/ctle_sp.cir"
PORTMAP="$HERE/netlists/ctle_sp_ports.json"

case "$OUT" in
  "$HOME"/s2r_runs/?*) rm -rf "$OUT" ;;
  *) echo "refusing to clean unexpected OUT: $OUT" >&2; exit 1 ;;
esac
mkdir -p "$OUT"

hr()  { printf '\n\033[1m%s\033[0m\n%s\n' "$1" "$(printf '=%.0s' {1..72})"; }
say() { printf '  %s\n' "$*"; }
beat(){ [ "${DEMO_PAUSE:-0}" = "1" ] && { printf '\n  [enter] '; read -r _; }; return 0; }

# PREFLIGHT NAMES EVERY MISSING PIECE, not the first one. A demo that
# stops at the first absence makes a reader fix one thing, re-run, and
# find the next.
missing=0
for f in "$NGSPICE" "$XEZIM" "$NETLIST" "$PORTMAP" "$S2R"; do
  [ -e "$f" ] || { echo "missing: $f"; missing=1; }
done
if ! "$NGSPICE" -v 2>&1 | grep -qi 'ngspice-[0-9]'; then
  echo "missing: $NGSPICE does not report an ngspice version"; missing=1
fi
# .sp analysis and RF ports arrived in ngspice 42; this demo needs them
# and a four-port sweep, so the version is checked rather than assumed.
ngver="$("$NGSPICE" -v 2>&1 | sed -n 's/.*ngspice-\([0-9][0-9]*\).*/\1/p' | head -1)"
if [ -n "$ngver" ] && [ "$ngver" -lt 42 ] 2>/dev/null; then
  echo "missing: ngspice $ngver is too old for .sp analysis (needs 42+)"
  missing=1
fi
HAVE_PLOTS=1
if ! "$PYPLOT" -c 'import matplotlib' >/dev/null 2>&1; then
  if python3 -c 'import matplotlib' >/dev/null 2>&1; then
    PYPLOT=python3
  else
    HAVE_PLOTS=0
    echo "note: no matplotlib on $PYPLOT or python3, so act 4 prints its"
    echo "      numbers and skips the overlay PNGs. Everything else runs."
    echo "      pip install 'spice2rnm[plots]'  (or set PYPLOT=...)"
  fi
fi
[ "$missing" = 0 ] || exit 1
cd "$S2R" || exit 1

hr "0. What is being claimed"
say "A CTLE: a differential pair degenerated by a parallel RS/CS, which"
say "boosts high frequency to undo a lossy channel. Four ports: in+/in-"
say "at 50 ohm, out+/out- at 1 kohm, which is the load the drains are."
echo
sed -n '/^VIP/,/^RD2/p' "$NETLIST" | sed 's/^/    /'
echo
say "CLAIMED:     SDD21, the differential transmission, is modelled."
say "NOT CLAIMED: SDD11, SDD22, SCD21, SDC21 are measured and reported."
beat

hr "1. The transistors' S-parameters"
say "ngspice's own .sp analysis, four RF ports, 81 points to 10 GHz."
say "Each port is biased at its net's own operating point, so no DC"
say "current flows through its reference impedance and the sweep"
say "linearises about the point the design actually has."
echo
python3 -m spice2rnm "$NETLIST" \
  --sparam-ports "$PORTMAP" --sparam-measure \
  --out-dir "$OUT/measure" --ngspice-bin "$NGSPICE" 2>&1 | sed 's/^/    /'
rc=${PIPESTATUS[0]}
if [ "$rc" -ne 0 ]; then
  say ""; say "THE MEASUREMENT FAILED (exit $rc). Nothing below would be"
  say "from this run, so stopping rather than reporting stale numbers."
  exit 1
fi
echo
say "The four-port file is Touchstone 2.0, because version 1 carries one"
say "reference impedance for a whole file and these ports are 50/50/1k/1k:"
echo
sed -n '/\[Version\]/,/\[Network Data\]/p' "$OUT/measure/ctle_sp.s4p" | sed 's/^/    /'
beat

hr "2. Characterise under the same ports, and generate the model"
say "The same deck, the same port sources, built by the same function --"
say "only the analysis card differs. A port is a real impedance at a"
say "node: ngspice applies it in the DC solution and in a plain .ac run,"
say "not only in .sp, so a model fitted without them would be a model of"
say "a different circuit."
say ""
say "This one command does acts 2, 3 and 4: it re-measures the"
say "transistors, fits and generates the model under those ports,"
say "simulates the generated SystemVerilog, and compares. One run, so"
say "both sides of the comparison come from one set of terminations."
echo
T0=$(date +%s)
python3 -m spice2rnm "$NETLIST" \
  --sparam-ports "$PORTMAP" --sparam-verify \
  --out-dir "$OUT" --ngspice-bin "$NGSPICE" --xezim-bin "$XEZIM" \
  > "$OUT/verify.log" 2>&1
rc=$?
sed -n '/\[2\/4\]/,/\[3\/4\]/p' "$OUT/verify.log" | sed 's/^/    /'
if [ "$rc" -ne 0 ] && ! grep -q 'VERDICT: PASS' "$OUT/verify.log"; then
  say ""; say "THE RUN FAILED (exit $rc). Last lines:"
  tail -12 "$OUT/verify.log" | sed 's/^/    /'
  exit 1
fi
echo
say "The fitted zero and pole, against the arithmetic of the schematic:"
say "  1/(2 pi RS CS)               = 99.47 MHz"
say "  (1 + gm RS/2)/(2 pi RS CS)   = 165.8 MHz"
beat

hr "3. Measure the SHIPPED MODEL, in the simulator"
say "Not FittedTF.eval(). The model is driven with a sine at each"
say "frequency and its amplitude and phase are read out by I/Q"
say "demodulation over a whole number of periods -- so what is measured"
say "is the model that ships, discretisation and all."
echo
sed -n '/\[3\/4\]/,/\[4\/4\]/p' "$OUT/verify.log" | sed 's/^/    /'
echo
say "The stimulus step is capped at the model's OWN integration step."
say "Driven more coarsely than that, anything the model does inside one"
say "step has finished before the next sample: at 1 MHz its phase read"
say "as exactly -180.000000 degrees, and its real -640 ps group delay"
say "measured as zero."
beat

hr "4. The comparison"
sed -n '/against the agreed bars/,/^$/p' "$OUT/verdict.txt" | sed 's/^/    /'
grep -E '^VERDICT' "$OUT/verdict.txt" | sed 's/^/    /'
echo
say "Worst over the whole sweep, including where the model cannot"
say "represent the response at all:"
sed -n '/over the WHOLE swept band/,/^$/p' "$OUT/verdict.txt" | sed 's/^/    /'
if [ "$HAVE_PLOTS" = 1 ]; then
  echo
  "$PYPLOT" "$S2R/work/plot_sparams.py" "$OUT" 2>&1 | sed 's/^/    /'
else
  say ""
  say "(no matplotlib: the overlay PNGs are skipped. sdd21_compare.csv"
  say " holds every number that would have been drawn.)"
fi
beat

hr "5. What is NOT modelled"
say "Measured from the transistors, printed because a figure that is"
say "simply absent reads as a figure that was fine."
echo
sed -n '/measured, not modelled/,$p' "$OUT/verdict.txt" | sed 's/^/    /'
echo
say "SDD11 and the two mode-conversion terms are exactly zero here"
say "because this deck is perfectly symmetric and its 100 ohm"
say "termination IS the differential reference. True measurements, and"
say "uninformative ones -- which is itself worth saying out loud."
echo
say "elapsed: $(( $(date +%s) - T0 )) s"
say ""
say "files in $OUT:"
ls -1 "$OUT" | sed 's/^/    /'
